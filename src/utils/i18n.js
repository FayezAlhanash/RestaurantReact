export function translate(key) {
    const language = getAppLanguage();
    return (
        translations[language]?.[key] ||
        (language === "ar" ? staticPhraseTranslations[key] : undefined) ||
        englishFallbacks[key] ||
        key
    );
}

export function translateStaticText(text, language = getAppLanguage()) {
    if (language !== "ar" || typeof text !== "string") return text;

    const normalizedText = text.replace(/\s+/g, " ").trim();
    if (!normalizedText) return text;

    if (staticPhraseTranslations[normalizedText]) {
        return text.replace(normalizedText, staticPhraseTranslations[normalizedText]);
    }

    for (const [pattern, replacement] of dynamicPhraseRules) {
        if (pattern.test(normalizedText)) {
            return text.replace(normalizedText, normalizedText.replace(pattern, replacement));
        }
    }

    return text;
}

export function useTranslation() {
    const [language, setLanguage] = useState(() => getAppLanguage());

    useEffect(() => {
        const handleLanguageChange = (event) => {
            setLanguage(event.detail || getAppLanguage());
        };

        window.addEventListener("app-language-change", handleLanguageChange);
        return () => window.removeEventListener("app-language-change", handleLanguageChange);
    }, []);

    const t = useCallback(
        (key) =>
            translations[language]?.[key] ||
            (language === "ar" ? staticPhraseTranslations[key] : undefined) ||
            englishFallbacks[key] ||
            key,
        [language]
    );

    return { language, t };
}
